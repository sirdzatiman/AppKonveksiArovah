    void setActiveMenu(JPanel active) {

        JPanel[] menu = {
            pnlDasboard,
            pnlTransaksi,
            pnlPesanan,
            pnlPengeluaran,
            pnlLaporan,
            pnlProfil,
            pnlLogout
        };

        for (JPanel p : menu) {

            Color warna = (p == active)
                    ? Color.decode("#F7CBD5")
                    : Color.decode("#FBDDE3");

            p.setBackground(warna);
            p.setOpaque(true);

            p.setBorder(new FlatLineBorder(
                    new Insets(0, 0, 0, 0),
                    warna,
                    1f,
                    15
            ));
        }
    }

    void panelLengkung(JPanel p) {
        p.setBorder(new FlatLineBorder(
                new Insets(0, 0, 0, 0),
                p.getBackground(),
                1f,
                15
        ));
    }

